-- Dynamic batch catalog and account access controls.
-- Run after 004_automatic_tally_ratios.sql in the Supabase SQL Editor.

BEGIN;

CREATE TABLE IF NOT EXISTS public.batches (
 batch_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(40) NOT NULL UNIQUE CHECK (name ~ '^[A-Za-z][A-Za-z -]{1,39}$'),
 student_year_prefix varchar(4) NOT NULL UNIQUE CHECK (student_year_prefix ~ '^[0-9]{4}$'),
 year_level varchar(3) NOT NULL CHECK (year_level IN ('2nd','3rd','4th')),
 theme_color varchar(7) NOT NULL CHECK (theme_color ~ '^#[0-9A-Fa-f]{6}$'),
 logo_path text NOT NULL DEFAULT '/logos/mudernize-logo.png',
 is_active boolean NOT NULL DEFAULT true,
 created_by uuid REFERENCES public.users(user_id),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.batches(name,student_year_prefix,year_level,theme_color,logo_path)
VALUES
